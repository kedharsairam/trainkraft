RCON = (0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)


def _xtime(b):
    return ((b << 1) & 0xFF) ^ (0x1B if b & 0x80 else 0)


def _gmul(a, b):
    p = 0
    while b:
        if b & 1:
            p ^= a
        a = _xtime(a)
        b >>= 1
    return p


def expand_key(key16):
    """AES-128 key expansion: 16-byte key -> 44 32-bit round words."""
    if len(key16) != 16:
        raise ValueError("AES-128 needs a 16-byte key, got %d" % len(key16))
    w = [int.from_bytes(key16[i:i + 4], "big") for i in range(0, 16, 4)]
    for i in range(4, 44):
        t = w[i - 1]
        if i % 4 == 0:
            t = (
                (SBOX[(t >> 16) & 0xFF] << 24)
                | (SBOX[(t >> 8) & 0xFF] << 16)
                | (SBOX[t & 0xFF] << 8)
                | SBOX[(t >> 24) & 0xFF]
            ) ^ (RCON[i // 4 - 1] << 24)
        w.append(w[i - 4] ^ t)
    return w


def _add_round_key(state, w, rnd):
    for c in range(4):
        word = w[4 * rnd + c]
        for r in range(4):
            state[r + 4 * c] ^= (word >> (24 - 8 * r)) & 0xFF


def _shift_rows_fwd(state):
    out = [0] * 16
    for r in range(4):
        for c in range(4):
            out[r + 4 * c] = state[r + 4 * ((c + r) % 4)]
    return out


def _shift_rows_inv(state):
    out = [0] * 16
    for r in range(4):
        for c in range(4):
            out[r + 4 * c] = state[r + 4 * ((c - r) % 4)]
    return out


def _mix_columns(state):
    for c in range(4):
        a0, a1, a2, a3 = (state[c * 4 + r] for r in range(4))
        state[c * 4 + 0] = _gmul(a0, 2) ^ _gmul(a1, 3) ^ a2 ^ a3
        state[c * 4 + 1] = a0 ^ _gmul(a1, 2) ^ _gmul(a2, 3) ^ a3
        state[c * 4 + 2] = a0 ^ a1 ^ _gmul(a2, 2) ^ _gmul(a3, 3)
        state[c * 4 + 3] = _gmul(a0, 3) ^ a1 ^ a2 ^ _gmul(a3, 2)
    return state


def _inv_mix_columns(state):
    for c in range(4):
        a0, a1, a2, a3 = (state[c * 4 + r] for r in range(4))
        state[c * 4 + 0] = _gmul(a0, 14) ^ _gmul(a1, 11) ^ _gmul(a2, 13) ^ _gmul(a3, 9)
        state[c * 4 + 1] = _gmul(a0, 9) ^ _gmul(a1, 14) ^ _gmul(a2, 11) ^ _gmul(a3, 13)
        state[c * 4 + 2] = _gmul(a0, 13) ^ _gmul(a1, 9) ^ _gmul(a2, 14) ^ _gmul(a3, 11)
        state[c * 4 + 3] = _gmul(a0, 11) ^ _gmul(a1, 13) ^ _gmul(a2, 9) ^ _gmul(a3, 14)
    return state


def encrypt_block(block16, round_words):
    if len(block16) != 16:
        raise ValueError("block must be 16 bytes")
    s = list(block16)
    _add_round_key(s, round_words, 0)
    for rnd in range(1, 10):
        s = [SBOX[b] for b in s]
        s = _shift_rows_fwd(s)
        s = _mix_columns(s)
        _add_round_key(s, round_words, rnd)
    s = [SBOX[b] for b in s]
    s = _shift_rows_fwd(s)
    _add_round_key(s, round_words, 10)
    return bytes(s)


def decrypt_block(block16, round_words):
    if len(block16) != 16:
        raise ValueError("block must be 16 bytes")
    s = list(block16)
    _add_round_key(s, round_words, 10)
    for rnd in range(9, 0, -1):
        s = _shift_rows_inv(s)
        s = [INV_SBOX[b] for b in s]
        _add_round_key(s, round_words, rnd)
        s = _inv_mix_columns(s)
    s = _shift_rows_inv(s)
    s = [INV_SBOX[b] for b in s]
    _add_round_key(s, round_words, 0)
    return bytes(s)


def _pkcs7_pad(data):
    n = 16 - (len(data) % 16)
    return data + bytes([n]) * n


def _pkcs7_unpad(data):
    if not data or len(data) % 16 != 0:
        raise ValueError("bad padded length")
    n = data[-1]
    if n < 1 or n > 16 or data[-n:] != bytes([n]) * n:
        raise ValueError("bad PKCS7 padding")
    return data[:-n]


def aes_cbc_encrypt(plaintext, key16, iv16):
    if len(iv16) != 16:
        raise ValueError("AES-CBC needs a 16-byte IV")
    rk = expand_key(key16)
    out = bytearray()
    prev = bytes(iv16)
    for i in range(0, len(_pkcs7_pad(plaintext)), 16):
        blk = _pkcs7_pad(plaintext)[i:i + 16]
        blk = bytes(a ^ b for a, b in zip(blk, prev))
        enc = encrypt_block(blk, rk)
        out += enc
        prev = enc
    return bytes(out)


def aes_cbc_decrypt(ciphertext, key16, iv16):
    if len(ciphertext) % 16 != 0 or not ciphertext:
        raise ValueError("ciphertext length must be a non-empty multiple of 16")
    if len(iv16) != 16:
        raise ValueError("AES-CBC needs a 16-byte IV")
    rk = expand_key(key16)
    out = bytearray()
    prev = bytes(iv16)
    for i in range(0, len(ciphertext), 16):
        dec = decrypt_block(ciphertext[i:i + 16], rk)
        out += bytes(a ^ b for a, b in zip(dec, prev))
        prev = ciphertext[i:i + 16]
    return _pkcs7_unpad(bytes(out))


# --------------------------------------------------------------------------
# NTES payload layer (mirrors NtesCrypto.encrypt / decrypt)
# --------------------------------------------------------------------------

def encrypt_payload(data, key, iv, sckey):
    """`"<MD5(data+sckey).upper()>#<hex(base64(AES-CBC(data))).upper()>"`.

    `data` str; `key`/`iv` 16-byte ASCII; `sckey` bytes (hex string bytes).
    """
    raw = data.encode("utf-8")
    digest = hashlib.md5(raw + sckey).hexdigest().upper()
    ct = aes_cbc_encrypt(raw, key, iv)
    enc = binascii.hexlify(base64.b64encode(ct)).decode("ascii").upper()
    return digest + "#" + enc


def decrypt_response(token, key, iv):
    """Inverse of [encrypt_payload]; accepts full `"HASH#ENC"` or bare ENC."""
    if not token:
        raise ValueError("empty input")
    enc = token.split("#", 1)[-1]  # everything after first "#", like Kotlin
    cipher = base64.b64decode(binascii.unhexlify(enc.encode("ascii")))
    return aes_cbc_decrypt(cipher, key, iv).decode("utf-8")


def load_keys(path):
    """Load `ntes-keys.json` -> (key16, iv16, sckey_bytes, endpoint)."""
    with open(path, "r", encoding="utf-8") as f:
        obj = json.load(f)
    for field in ("key", "iv", "sckey"):
        if not obj.get(field):
            raise ValueError("ntes-keys.json: missing/blank field %r" % field)
    key = obj["key"].encode("ascii")
    iv = obj["iv"].encode("ascii")
    if len(key) != 16 or len(iv) != 16:
        raise ValueError("ntes-keys.json: key/iv must be 16 ASCII chars each")
    return key, iv, obj["sckey"].encode("ascii"), obj.get(
        "endpoint", "https://enquiry.indianrail.gov.in/crisns/AppServAnd"
    )
